"""Upgrade handler — /upgrade command for self-updating ccgram via uv.

Runs `uv tool upgrade ccgram`, reports the result, and requests the runtime to
restart the bot process via os.execv() if an upgrade was installed. If the host
has no restart callback, it asks the operator to restart the bot manually.
Existing tmux windows are untouched since only the bot process restarts.

Key function: upgrade_command().
"""

from __future__ import annotations

from typing import TYPE_CHECKING
import asyncio
import structlog
import re

from telegram import Update
from ..config import config
from .messaging_pipeline.message_sender import safe_edit, safe_reply

if TYPE_CHECKING:
    from telegram.ext import ContextTypes

logger = structlog.get_logger()

_UPGRADE_TIMEOUT = 90

# uv prints "Updated ccgram v0.1.dev862 -> v0.1.dev863" when ccgram itself
# changed, and only "Modified ccgram environment" plus " + pkg==ver" lines
# when a dependency moved and ccgram did not.
_VERSION_RE = re.compile(r"ccgram v\S+ -> v(\S+)")
_ADDED_PACKAGE_RE = re.compile(r"^ \+ (\S+)", re.MULTILINE)


def _upgrade_summary(output: str, current_version: str) -> str:
    """Say what ``uv tool upgrade`` changed, for the reply and the log."""
    match = _VERSION_RE.search(output)
    if match:
        return f"Upgraded to v{match.group(1)}"
    packages = _ADDED_PACKAGE_RE.findall(output)
    if packages:
        return (
            f"ccgram v{current_version} unchanged; "
            f"updated dependencies: {', '.join(packages)}"
        )
    return "Upgraded"


async def upgrade_command(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    """Handle /upgrade — upgrade ccgram via uv and restart if needed."""
    user = update.effective_user
    if not user or not update.message:
        return
    if not config.is_user_allowed(user.id):
        await safe_reply(update.message, "You are not authorized to use this bot.")
        return

    # Lazy: __version__ is generated by hatch-vcs and needed only when
    # /upgrade runs.
    from .. import __version__

    msg = await update.message.reply_text("\u23f3 Checking for updates...")

    try:
        proc = await asyncio.create_subprocess_exec(
            "uv",
            "tool",
            "upgrade",
            "ccgram",
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE,
        )
    except FileNotFoundError:
        await safe_edit(
            msg, "\u274c `uv` not found. Is ccgram installed via `uv tool install`?"
        )
        return
    except OSError as exc:
        await safe_edit(msg, f"\u274c Upgrade failed: {exc}")
        return

    try:
        async with asyncio.timeout(_UPGRADE_TIMEOUT):
            stdout, stderr = await proc.communicate()
    except TimeoutError:
        proc.kill()
        await safe_edit(msg, "\u274c Upgrade timed out after 60s.")
        return

    output = (stdout or b"").decode() + (stderr or b"").decode()

    if proc.returncode != 0:
        detail = output.strip()[:200] if output.strip() else "unknown error"
        await safe_edit(
            msg, f"\u274c Upgrade failed (exit {proc.returncode}):\n`{detail}`"
        )
        return

    # Detect whether an upgrade actually happened
    # uv output: "Nothing to upgrade" when up-to-date,
    # "Upgraded ccgram v0.2.0 -> v0.2.1" when upgraded
    if "nothing to upgrade" in output.lower():
        await safe_edit(msg, f"\u2705 Already up to date (v{__version__}).")
        return

    summary = _upgrade_summary(output, __version__)

    # Lazy: bot is fully imported by the time /upgrade runs; hoisting cycles
    from ..bot import REQUEST_RESTART_KEY, arm_shutdown_watchdog

    request_restart = context.bot_data.get(REQUEST_RESTART_KEY)
    if not callable(request_restart):
        await safe_edit(
            msg,
            f"\u2705 {summary}, but automatic restart is unavailable. "
            "Restart ccgram manually to finish the upgrade.",
        )
        return

    await safe_edit(msg, f"\u2705 {summary}. Restarting...")
    logger.info("Upgrade complete, scheduling restart", summary=summary)

    request_restart()
    # This stop path never reaches the signal handler; arm before stop() so a
    # wedge there still exits and the supervisor can restart.
    arm_shutdown_watchdog()
    context.application.stop_running()
